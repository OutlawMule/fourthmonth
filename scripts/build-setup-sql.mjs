#!/usr/bin/env node
// Builds supabase/SETUP_ALL_IN_ONE.sql: the migrations in supabase/migrations, in order, joined into ONE
// file that can be pasted into the Supabase SQL Editor and run once.
//
//   npm run build:setup-sql
//
// tests/setupSql.test.js fails if the file on disk no longer matches the migrations, and also applies the
// whole file to a fresh PostgreSQL engine to prove it runs.
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
export const MIGRATIONS = join(ROOT, 'supabase', 'migrations');
export const OUT = join(ROOT, 'supabase', 'SETUP_ALL_IN_ONE.sql');

const RULE = '-- ====================================================================';

function header(files) {
  return [
    '-- MULE x PRINCESS: the complete database setup in ONE file.',
    '--',
    '-- How to use it (on a new Supabase project):',
    '--   1. Supabase dashboard -> SQL Editor -> New query.',
    '--   2. Paste this whole file and press Run.',
    '--   3. If the editor warns about "destructive operations", that is expected: the script replaces',
    '--      triggers that it creates itself. Confirm and run it.',
    '--   4. Wait for "Success". Then Table Editor should list: profiles, relationships,',
    '--      relationship_members, invitations, invitation_attempts, game_progress, story_memories,',
    '--      questions, answers and answer_signals, each with RLS enabled.',
    '--',
    '-- Running it again later is safe: it only creates what is missing and refreshes the rules and the',
    '-- question list. It never deletes anyone\'s answers.',
    '--',
    `-- It is exactly these ${files.length} files from supabase/migrations, in this order, joined together:`,
    ...files.map((f) => `--   ${f}`),
    '--',
    '-- Do not edit this file by hand: change the migrations and run  npm run build:setup-sql',
    '',
  ].join('\n');
}

/** The combined script as text. `dir` is only changed by tests. */
export function buildSetupSql(dir = MIGRATIONS) {
  const files = readdirSync(dir).filter((f) => /^\d+_.+\.sql$/.test(f)).sort();
  const parts = [header(files)];
  for (const f of files) {
    const body = readFileSync(join(dir, f), 'utf8').replace(/\r\n/g, '\n');
    parts.push(`${RULE}\n-- ${f}\n${RULE}\n${body.endsWith('\n') ? body : `${body}\n`}`);
  }
  return parts.join('\n');
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const text = buildSetupSql();
  writeFileSync(OUT, text);
  process.stdout.write(`Wrote ${OUT}\n${text.split('\n').length} lines, ${Buffer.byteLength(text)} bytes\n`);
}
